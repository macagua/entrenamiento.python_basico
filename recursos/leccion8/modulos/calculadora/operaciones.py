"""Este módulo contiene funciones para realizar cálculos matemáticos básicos."""


def suma(a, b):
    """
    Esta función suma dos números y devuelve el resultado.
    """
    resultado = a + b
    return resultado


def resta(a, b):
    """
    Esta función resta dos números y devuelve el resultado.
    """
    resultado = a - b
    return resultado
